// File templates of the world-scaffold hook (pure; no I/O, no LLM calls, ASCII only).
// Every template uses only canary values and reserved domains, and no hidden character.

/** The files the scaffold creates, relative to `worlds/<name>/`, in creation order. */
export const SCAFFOLD_FILES = Object.freeze([
  'world.config.ts',
  'tests/contract.test.ts',
  'wards.yaml',
  'README.md',
]);

/** Rule that a world name must satisfy (Requirement 16 criterion 1). */
export const WORLD_NAME_PATTERN = /^[a-z][a-z0-9-]{0,63}$/;

/** Default number of examples of the generated contract test in a Short_Run. */
export const CONTRACT_NUM_RUNS_SHORT = 100;

/** Number of examples of the generated contract test in a Nightly_Run. */
export const CONTRACT_NUM_RUNS_NIGHTLY = 10_000;

/**
 * @param {string} name a valid world name
 * @returns {string}
 */
export function worldConfigTemplate(name) {
  return [
    '// World registration (kiro-integration convention): default export',
    '// { id, deterministic, wardsFile, create }. `wardsFile` is a path string only; it is never imported.',
    '//',
    '// deterministic: false on purpose. P2 (a plan that passes produces the same diff when run for real)',
    '// is claimed only after this world is shown to be deterministic. Set it to true only then.',
    '',
    'function create(): never {',
    `  throw new Error('implement create() of world ${name}: return an object with the six World functions');`,
    '}',
    '',
    'export default {',
    `  id: '${name}',`,
    '  deterministic: false,',
    "  wardsFile: './wards.yaml',",
    '  create,',
    '} as const;',
    '',
  ].join('\n');
}

/**
 * @param {string} name a valid world name
 * @returns {string}
 */
export function contractTestTemplate(name) {
  return [
    `// Contract test of world ${name} (generated by world-scaffold).`,
    '// Run from the repository root with the root vitest.worlds.config.ts. `describe`, `it`, and',
    '// `expect` are vitest globals (the config sets `globals: true`).',
    '// The world registers with deterministic: false, so P2 is not exercised until world.config.ts sets',
    '// it to true after the world is shown to be deterministic.',
    "import { readFileSync } from 'node:fs';",
    "import * as fc from 'fast-check';",
    "import { verifyWorld } from '@ghost-run/core/verify';",
    "import { parseWards } from '@ghost-run/wards-config';",
    "import config from '../world.config.js';",
    '',
    "const { env } = process;",
    `const NUM_RUNS = env.GHOST_PBT_MODE === 'nightly' ? ${CONTRACT_NUM_RUNS_NIGHTLY} : ${CONTRACT_NUM_RUNS_SHORT};`,
    '',
    'function assertWorldConfigShape(c: Record<string, unknown>): void {',
    "  if (typeof c.id !== 'string' || c.id === '') throw new Error('world.config: id must be a non-empty string');",
    "  if (typeof c.deterministic !== 'boolean') throw new Error('world.config: deterministic must be a boolean');",
    "  if (typeof c.wardsFile !== 'string') throw new Error('world.config: wardsFile must be a path string');",
    "  if (typeof c.create !== 'function') throw new Error('world.config: create must be a function');",
    '}',
    '',
    `describe('world ${name}', () => {`,
    "  it('has a valid registration', () => {",
    '    assertWorldConfigShape(config);',
    `    expect(config.id).toBe('${name}');`,
    '  });',
    '',
    "  it('passes the registration gate (verifyWorld)', async () => {",
    "    const parsed = parseWards(readFileSync(new URL('../wards.yaml', import.meta.url), 'utf8'));",
    "    if (!parsed.ok) throw new Error('wards.yaml does not parse');",
    '    const world = await config.create();',
    '    await verifyWorld(world as never, {',
    '      id: config.id,',
    '      deterministic: config.deterministic,',
    '      wardSet: parsed.wardSet,',
    '      actionArb: fc.constant(undefined).map(() => {',
    `        throw new Error('define actionArb for ${name}');`,
    '      }),',
    '      numRuns: NUM_RUNS,',
    '    });',
    '  });',
    '});',
    '',
  ].join('\n');
}

/** @returns {string} */
export function wardsTemplate() {
  return [
    '# Wards of this world. An empty list passes every plan; add wards before relying on a verdict.',
    '# Kinds: path, sql, egress, physics (see the world-contract steering).',
    'wards: []',
    '',
  ].join('\n');
}

/**
 * @param {string} name a valid world name
 * @returns {string}
 */
export function readmeTemplate(name) {
  return [
    `# World: ${name}`,
    '',
    'Status: scaffold only. Implement the six `World<S, A>` functions, then save a file in this',
    'folder to run contract-pbt.',
    '',
    '## The six functions',
    '',
    '| Function | Contract |',
    '|---|---|',
    '| `snapshot()` | Returns a deep copy of the current state. Must not modify reality. |',
    '| `step(s, a)` | Applies one action to a snapshot. Must not modify reality or the input snapshot. |',
    '| `diff(before, after)` | Returns the minimal set of `Change` objects between two snapshots. |',
    '| `render(s)` | Returns a `Scene` for the UI kit. Must be pure. |',
    '| `fingerprint()` | Returns a hash of real-world state (P1 isolation check). |',
    '| `effectsOutside(a)` | Returns `Effect[]` for actions that reach outside the copy. |',
    '',
    '## Checklist',
    '',
    '- [ ] All six functions implemented',
    '- [ ] `snapshot()` leaves reality unchanged (P1)',
    '- [ ] `step()` does not mutate the input snapshot',
    '- [ ] `diff()` covers every change type of this world',
    '- [ ] `effectsOutside()` is non-empty for every action that leaves the copy',
    '- [ ] `actionArb` defined in `tests/contract.test.ts`',
    '- [ ] P1, P2 (if deterministic), P3, and the ward properties pass',
    '- [ ] Wards of this world written in `wards.yaml`',
    '',
    '## Claims',
    '',
    '| Property | Claimed |',
    '|---|---|',
    '| P1 | After the checklist passes, inside the Docker box only |',
    '| P2 | Not claimed (`deterministic: false` in `world.config.ts`) until the world is shown to be deterministic |',
    '| P3 | After the checklist passes |',
    '| P4 to P8 | Where the ward kinds of this world apply |',
    '',
  ].join('\n');
}

/**
 * Template text per file.
 * @param {string} name a valid world name
 * @returns {Record<string, string>} keyed by the entries of SCAFFOLD_FILES
 */
export function renderTemplates(name) {
  return {
    'world.config.ts': worldConfigTemplate(name),
    'tests/contract.test.ts': contractTestTemplate(name),
    'wards.yaml': wardsTemplate(),
    'README.md': readmeTemplate(name),
  };
}
